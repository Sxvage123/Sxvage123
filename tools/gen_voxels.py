#!/usr/bin/env python3
"""Builds voxel brainrots from voxel_specs.py into shared/common/BrainrotModels.luau + optional preview JSON."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from voxel import Vox
import voxel_specs

RES = 0.35
results = {}
for name, fn in voxel_specs.C.items():
    v = Vox(res=RES)
    fn(v)
    boxes = v.boxes()
    lo, hi = v.bounds_of_fill()
    results[name] = {"boxes": boxes, "palette": v.palette[1:], "lo": v.lo.tolist(), "fill_lo": lo.tolist(), "fill_hi": hi.tolist()}
    print(f"{name}: {len(boxes)} parts, {int((v.grid > 0).sum())} voxels", file=sys.stderr)
if len(sys.argv) > 1:
    json.dump({"res": RES, "chars": results}, open(sys.argv[1], "w"))

# ---------------------------------------------------------------- Luau module
from brainrot_specs import ALIASES  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..")
L = [
    "-- GENERATED by tools/gen_voxels.py from tools/voxel_specs.py. Edit the specs, not this file.",
    "-- Voxel (Steal a Brainrot style) builds of the Italian brainrot characters.",
    "-- Feet stand on y = 0 and every character faces -Z.",
    "local BrainrotModels = {}",
    "",
    f"local RES = {RES}",
    "",
    "-- origin = grid corner (studs); fill = filled cell range; palette = rgb list;",
    "-- boxes = flat list of (i, j, k, sizeI, sizeJ, sizeK, paletteIndex) in grid cells.",
    "local SPECS = {",
]
for name, r in results.items():
    pal = ", ".join("{%d,%d,%d}" % tuple(c) for c in r["palette"])
    flat = ",".join(str(x) for b in r["boxes"] for x in b)
    L.append(f'\t{name} = {{ origin = {{ {", ".join(str(x) for x in r["lo"])} }}, fill = {{ {", ".join(str(x) for x in r["fill_lo"] + r["fill_hi"])} }},')
    L.append(f"\t\tpalette = {{ {pal} }},")
    L.append(f"\t\tboxes = {{ {flat} }} }},")
L.append("}")
L.append("")
L.append("BrainrotModels.Aliases = {")
for k, val in ALIASES.items():
    L.append(f'\t{k} = "{val}",')
L.append("}")
L.append('''
function BrainrotModels.Resolve(id: string): string?
	if SPECS[id] then
		return id
	end
	local alias = BrainrotModels.Aliases[id]
	return if alias and SPECS[alias] then alias else nil
end

function BrainrotModels.Has(id: string): boolean
	return BrainrotModels.Resolve(id) ~= nil
end

-- Builds the character as a Model whose PrimaryPart is an invisible anchored "Root" box around it.
-- Every visible block is welded to Root, so moving Root moves the whole figure.
-- Attribute RootHeight = distance from Root's centre down to the feet.
-- opts.Scale (number), opts.Tint (Color3 blended over every block), opts.Neon (bool), opts.Anchored (default true)
function BrainrotModels.Build(id: string, opts: { Scale: number?, Tint: Color3?, Neon: boolean?, Anchored: boolean? }?): (Model, BasePart)
	local key = BrainrotModels.Resolve(id)
	assert(key, "No brainrot model for " .. tostring(id))
	local spec = SPECS[key]
	local o = opts or {}
	local scale = o.Scale or 1
	local res = RES * scale
	local origin = Vector3.new(spec.origin[1], spec.origin[2], spec.origin[3]) * scale
	local f = spec.fill
	local lo = origin + Vector3.new(f[1], f[2], f[3]) * res
	local hi = origin + Vector3.new(f[4], f[5], f[6]) * res
	local center = (lo + hi) / 2

	local colors = {}
	for i, c in spec.palette do
		local color = Color3.fromRGB(c[1], c[2], c[3])
		if o.Tint then
			color = color:Lerp(o.Tint, 0.55)
		end
		colors[i] = color
	end

	local model = Instance.new("Model")
	model.Name = key
	local root = Instance.new("Part")
	root.Name = "Root"
	root.Size = hi - lo
	root.Transparency = 1
	root.CanCollide = false
	root.CanTouch = false
	root.Anchored = if o.Anchored == false then false else true
	root.CFrame = CFrame.new(center)
	root.Parent = model
	model.PrimaryPart = root

	local b = spec.boxes
	for n = 1, #b, 7 do
		local part = Instance.new("Part")
		part.Size = Vector3.new(b[n + 3], b[n + 4], b[n + 5]) * res
		part.CFrame = CFrame.new(origin + Vector3.new(b[n] + b[n + 3] / 2, b[n + 1] + b[n + 4] / 2, b[n + 2] + b[n + 5] / 2) * res)
		part.Color = colors[b[n + 6]]
		part.Material = if o.Neon then Enum.Material.Neon else Enum.Material.SmoothPlastic
		part.TopSurface = Enum.SurfaceType.Smooth
		part.BottomSurface = Enum.SurfaceType.Smooth
		part.CanCollide = false
		part.CanTouch = false
		part.CanQuery = false
		part.Massless = true
		part.Anchored = false
		local weld = Instance.new("WeldConstraint")
		weld.Part0 = root
		weld.Part1 = part
		weld.Parent = part
		part.Parent = model
	end
	model:SetAttribute("RootHeight", center.Y)
	return model, root
end

return BrainrotModels''')
open(os.path.join(ROOT, "shared/common/BrainrotModels.luau"), "w").write("\n".join(L) + "\n")
print("wrote BrainrotModels.luau", file=sys.stderr)
