#!/usr/bin/env python3
"""Generates shared/common/BrainrotModels.luau and a preview page from brainrot_specs.py."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import brainrot_specs as specs

ROOT = os.path.join(os.path.dirname(__file__), "..")
NAMES = {
    "tralalero": "Tralalero Tralala", "bombardiro": "Bombardiro Crocodilo", "tung": "Tung Tung Tung Sahur",
    "ballerina": "Ballerina Cappuccina", "chimpanzini": "Chimpanzini Bananini", "patapim": "Brr Brr Patapim",
    "lirili": "Lirili Larila", "cappuccino": "Cappuccino Assassino", "tim_cheese": "Tim Cheese",
    "noobini": "Noobini Pizzanini", "frigo": "Frigo Camelo", "cocofanto": "Cocofanto Elefanto",
    "la_vacca": "La Vacca Saturno Saturnita", "odin_din": "Odin Din Din Dun", "trippi": "Trippi Troppi",
    "fluri": "Fluriflura", "talpa": "Talpa di Fero", "svinina": "Svinina Bombardino", "pipi_kiwi": "Pipi Kiwi",
    "gangster": "Gangster Footera", "orangutini": "Orangutini Ananasini", "skibidi": "Skibidi Toilet",
    "garama": "Garama and Madundung",
}

def bounds(parts):
    lo, hi = [1e9] * 3, [-1e9] * 3
    for p in parts:
        r = max(p["size"]) / 2
        for i in range(3):
            lo[i] = min(lo[i], p["pos"][i] - r)
            hi[i] = max(hi[i], p["pos"][i] + r)
    lo[1] = 0
    return lo, hi

def fmt(x):
    return ("%.3f" % x).rstrip("0").rstrip(".") if x != int(x) else str(int(x))

lines = [
    "-- GENERATED by tools/gen_brainrots.py from tools/brainrot_specs.py. Edit the specs, not this file.",
    "-- Part-built look-alikes of the Italian brainrot characters. Feet stand on y = 0, faces look toward -Z.",
    "local BrainrotModels = {}",
    "",
    "-- Each part: shape, size xyz, position xyz, rgb, material, rotation xyz (degrees)",
    "local SPECS = {",
]
for cid, parts in specs.C.items():
    lo, hi = bounds(parts)
    lines.append(f'\t{cid} = {{ bounds = {{ {", ".join(fmt(v) for v in lo + hi)} }}, parts = {{')
    for p in parts:
        vals = [f'"{p["s"]}"'] + [fmt(v) for v in p["size"] + p["pos"]] + [str(int(c)) for c in p["c"]] + [f'"{p["m"]}"'] + [fmt(v) for v in p["r"]]
        lines.append("\t\t{ " + ", ".join(vals) + " },")
    lines.append("\t} },")
lines.append("}")
lines.append("")
lines.append("BrainrotModels.Aliases = {")
for k, v in specs.ALIASES.items():
    lines.append(f'\t{k} = "{v}",')
lines.append("}")
lines.append('''
function BrainrotModels.Resolve(id: string): string?
	if SPECS[id] then
		return id
	end
	local alias = BrainrotModels.Aliases[id]
	return if alias and SPECS[alias] then alias else nil
end

function BrainrotModels.Has(id: string): boolean
	return BrainrotModels.Resolve(id) ~= nil
end

-- Builds the character as a Model with an invisible anchored "Root" part (PrimaryPart) that every
-- visible part is welded to. Attribute RootHeight = distance from Root's centre down to the feet.
-- opts.Scale (number), opts.Tint (Color3 blended over every part), opts.Neon (bool), opts.Anchored (bool, default true)
function BrainrotModels.Build(id: string, opts: { Scale: number?, Tint: Color3?, Neon: boolean?, Anchored: boolean? }?): (Model, BasePart)
	local key = BrainrotModels.Resolve(id)
	assert(key, "No brainrot model for " .. tostring(id))
	local spec = SPECS[key]
	local o = opts or {}
	local scale = o.Scale or 1
	local b = spec.bounds
	local size = Vector3.new(b[4] - b[1], b[5] - b[2], b[6] - b[3]) * scale
	local center = Vector3.new((b[1] + b[4]) / 2, (b[2] + b[5]) / 2, (b[3] + b[6]) / 2) * scale

	local model = Instance.new("Model")
	model.Name = key
	local root = Instance.new("Part")
	root.Name = "Root"
	root.Size = size
	root.Transparency = 1
	root.CanCollide = false
	root.CanTouch = false
	root.Anchored = if o.Anchored == false then false else true
	root.CFrame = CFrame.new(center)
	root.Parent = model
	model.PrimaryPart = root

	for i, p in spec.parts do
		local shape, sx, sy, sz, px, py, pz = p[1], p[2] * scale, p[3] * scale, p[4] * scale, p[5] * scale, p[6] * scale, p[7] * scale
		local part = Instance.new("Part")
		part.Name = "P" .. i
		part.TopSurface = Enum.SurfaceType.Smooth
		part.BottomSurface = Enum.SurfaceType.Smooth
		part.CanCollide = false
		part.CanTouch = false
		part.CanQuery = false
		part.Massless = true
		part.Anchored = false
		local color = Color3.fromRGB(p[8], p[9], p[10])
		if o.Tint then
			color = color:Lerp(o.Tint, 0.6)
		end
		part.Color = color
		part.Material = if o.Neon then Enum.Material.Neon else (Enum.Material :: any)[p[11]]
		local cf = CFrame.new(px, py, pz) * CFrame.Angles(math.rad(p[12]), math.rad(p[13]), math.rad(p[14]))
		if shape == "ball" then
			part.Shape = Enum.PartType.Ball
			part.Size = Vector3.new(sx, sx, sx)
		elseif shape == "cyl" then
			-- Roblox cylinders run along X; specs run along Y.
			part.Shape = Enum.PartType.Cylinder
			part.Size = Vector3.new(sy, sx, sz)
			cf *= CFrame.Angles(0, 0, math.rad(90))
		else
			part.Size = Vector3.new(sx, sy, sz)
		end
		part.CFrame = cf
		local weld = Instance.new("WeldConstraint")
		weld.Part0 = root
		weld.Part1 = part
		weld.Parent = part
		part.Parent = model
	end
	model:SetAttribute("RootHeight", center.Y)
	return model, root
end

return BrainrotModels''')
out = os.path.join(ROOT, "shared/common/BrainrotModels.luau")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)

if len(sys.argv) > 1:
    # Preview page for checking the builds: argv[1] = output html, argv[2] = three.js source ("cdn" or a local file to inline)
    data = {cid: {"name": NAMES.get(cid, cid), "parts": parts} for cid, parts in specs.C.items()}
    three = '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>'
    if len(sys.argv) > 2 and sys.argv[2] != "cdn":
        three = "<script>" + open(sys.argv[2]).read() + "</script>"
    tpl = open(os.path.join(os.path.dirname(__file__), "brainrot_preview.html")).read()
    open(sys.argv[1], "w").write(tpl.replace("<!--THREE-->", three).replace("/*DATA*/null", json.dumps(data)))
    print("wrote", sys.argv[1])
