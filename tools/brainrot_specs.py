"""Part-by-part designs for every brainrot character.

Coordinates are studs: y is up, the feet stand on y = 0, and the character faces -Z (Roblox's front).
Shapes: "block", "ball" (uses size[0] as diameter), "cyl" (axis along Y; size = [diameter, height, diameter]).
rot is degrees (x, y, z), applied like CFrame.Angles.
Run tools/gen_brainrots.py after editing to regenerate the Luau module and the preview page.
"""
import math

def P(shape, size, pos, color, mat="SmoothPlastic", rot=(0, 0, 0)):
    return {"s": shape, "size": list(size), "pos": list(pos), "c": list(color), "m": mat, "r": list(rot)}

BLACK = (20, 20, 20); WHITE = (245, 245, 245); RED_MOUTH = (120, 20, 30); PINK = (255, 150, 170)

def eyes(sep, y, z, d=0.9, pupil=0.45, white=WHITE, angry=False):
    out = []
    for sx in (-1, 1):
        out.append(P("ball", [d] * 3, (sx * sep, y, z), white))
        out.append(P("ball", [pupil] * 3, (sx * sep, y, z - d * 0.35), BLACK))
        if angry:
            out.append(P("block", (d * 1.1, 0.18, 0.15), (sx * sep, y + d * 0.6, z - 0.05), BLACK, rot=(0, 0, -sx * 20)))
    return out

def sneaker(x, z, color=WHITE, accent=(40, 90, 255)):
    return [
        P("block", (1.1, 0.6, 1.8), (x, 0.3, z - 0.2), color),
        P("block", (1.15, 0.2, 1.85), (x, 0.08, z - 0.2), (60, 60, 60)),
        P("block", (1.16, 0.18, 0.9), (x, 0.38, z - 0.15), accent, rot=(0, 0, 12)),
    ]

def leg(x, z, top, color, d=0.55):
    h = top
    return P("cyl", (d, h, d), (x, h / 2, z), color)

def arm(start, end, color, d=0.45):
    sx, sy, sz = start; ex, ey, ez = end
    mid = ((sx + ex) / 2, (sy + ey) / 2, (sz + ez) / 2)
    dx, dy, dz = ex - sx, ey - sy, ez - sz
    length = math.sqrt(dx * dx + dy * dy + dz * dz)
    # CFrame.Angles(rx, 0, rz) applies rz first: Y -> (sin, cos, 0) leaning toward x, then rx swings it toward z.
    rz = -math.degrees(math.asin(max(-1.0, min(1.0, dx / length))))
    rx = math.degrees(math.atan2(dz, dy))
    return P("cyl", (d, length, d), mid, color, rot=(rx, 0, rz))

